def main() -> int:
    cards = json.loads((ROOT / "data" / "cards.json").read_text(encoding="utf-8"))["cards"]
    heroes = {n for n, c in cards.items() if c.get("category") == "英雄牌"}
    missing, extra = sorted(heroes - set(H)), sorted(set(H) - heroes)
    if missing or extra:
        print("缺：", missing, "多：", extra)
        return 1
    out = {n: {"carry_score": s, "why": w, "reviewed": True, "reviewer": "claude-main"} for n, (s, w) in H.items()}
    (ROOT / "data" / "hero_carry_reviewed.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"写入 {len(out)} 名英雄 -> data/hero_carry_reviewed.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
