def g(res: str, n=None, to: str = "", per: str = "") -> dict:
    """一项产出/消耗。n 可以是数字，也可以是算式说明；to = 作用对象；per = 频率（每回合/每场/每3次技能…）。"""
    d = {"res": res}
    if n is not None:
        d["n"] = n
    if to:
        d["to"] = to
    if per:
        d["per"] = per
    return d


def C(name: str, trig: str, gives=(), needs=(), cond: str = "", routes=(), scope: str = "通用",
      awaken: str = "", note: str = "", unsure: str = "") -> dict:
    return {"name": name, "trig": trig, "gives": list(gives), "needs": list(needs), "cond": cond,
            "routes": list(routes), "scope": scope, "awaken": awaken, "note": note, "unsure": unsure}
