def extend(ctx) -> None:
    """ctx: dict(add=..., NODES=..., SCOPES=..., TECHNIQUES=..., EDGE_TYPES=..., HROLES=..., HT=..., CARDS=...)"""
    add, NODES, SCOPES = ctx["add"], ctx["NODES"], ctx["SCOPES"]
    ctx["EDGE_TYPES"]["reacts_to"] = ("反应器：from 是“每当…时 / 每…次”类被动，对 to 这个事件（@ev:*）起反应。"
                                      "事件的额外触发源 → 反应器 用 amplifies（source=chain:<事件>，attrs.via）表达“触发器放大反应器”。")
    for ev, d in EVENTS.items():
        SCOPES[f"@ev:{ev}"] = {"kind": "event", "def": d}
    reactors = {}
    for node, ev, q, a in REACTORS:
        add(node, "reacts_to", f"@ev:{ev}", q, "chain_reactor", **a)
        reactors.setdefault(ev, []).append((node, q))
    for ev, srcs in EVENT_SOURCES.items():
        for s, q, kind in srcs:
            for r, rq in reactors.get(ev, []):
                if s != r:
                    add(s, "amplifies", r, q, f"chain:{ev}", via=f"@ev:{ev}", kind=kind, reactor_quote=rq)
    ctx["TECHNIQUES"].update(TECHNIQUES)
    for c, t, q, role in ENABLES:
        add(c, "enables", t, q, "chain_technique", role=role)
    for h, t, q, role in FITS:
        add(h, "fits_role", t, q, "chain_technique", role=role)
    # 按等级成长的装备 → 所有主C 候选（source=level_scaling）
    HROLES, HT = ctx["HROLES"], ctx["HT"]
    carries = sorted(h for h, r in HROLES.items()
                     if (set(r.get("combat_role") or []) & {"carry_phys", "carry_mag", "assassin"}) or (r.get("carry_value") or 0) >= 6)
    for item, (q, dmg, why) in LEVEL_SCALING.items():
        for h in carries:
            if dmg != "any" and HT.dmg_type(h) not in (dmg, "hybrid"):
                continue
            if item == "破阵战芒" and not (1 <= (NODES[h].get("quality") or 0) <= 3):
                continue
            add(item, "equip_fits", h, q, "level_scaling", why=why)
    ctx["LEVEL_SCALING_ITEMS"] = set(LEVEL_SCALING)
