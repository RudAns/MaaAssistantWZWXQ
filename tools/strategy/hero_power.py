def fight_damage(card: dict, a: dict, stage: int) -> float:
    pr = card.get("properties") or {}
    atk = max(pr.get("phyAttack", 0) or 0, pr.get("magAttack", 0) or 0) or 30
    aps = (pr.get("attackSpeed", 10000) or 10000) / 10000 * a.get("aspd", [1] * 4)[stage]
    crit = 1 + (pr.get("criticalRate", 0) or 0) / 10000 * .5
    mana_max, mana0 = pr.get("energy", 60) or 60, pr.get("initEnergy", 0) or 0
    regen = MANA_PER_ATTACK * aps * a.get("mana_mult", [1] * 4)[stage]
    ch = a.get("ch", 0)
    cast = a["cast"][stage]
    if stage == 3 and a.get("total100"):
        casts, t_cast, cast_total = 1, FIGHT_S, a["total100"]
    else:
        t_first = max(0.0, (mana_max - mana0) / regen)
        interval = mana_max / regen + ch
        casts = 0.0 if t_first >= FIGHT_S else 1 + (FIGHT_S - t_first - ch) / interval
        casts = max(0.0, min(casts, 1.0) if a.get("once") else casts)
        t_cast = casts * ch
        cast_total = casts * cast
    t_auto = max(0.0, FIGHT_S - t_cast)
    auto_total = aps * t_auto * a.get("auto", [100] * 4)[stage] * crit
    extra = a.get("extra", [0] * 4)[stage] * FIGHT_S
    rng = pr.get("attackDistance", 1) or 1
    surv = a.get("surv", [1.0 if rng >= 3 else .75] * 4)[stage]
    return atk * (cast_total * crit + auto_total + extra) / 100 * surv


def power_table() -> dict[str, dict]:
    cards = json.loads((ROOT / "data" / "cards.json").read_text(encoding="utf-8"))["cards"]
    out = {}
    for n, a in P.items():
        c = cards[n]
        out[n] = {f"L{lv}": round(fight_damage(c, a, i)) for i, lv in enumerate((1, 10, 40, 100))}
    return out


def main() -> int:
    t = power_table()
    for n, v in sorted(t.items(), key=lambda x: -x[1]["L40"]):
        print(f"{n:6s} " + "  ".join(f"{k}={v[k]:6d}" for k in ("L1", "L10", "L40", "L100")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
