# 升级奖励（2026-09-22 补充）
# ---------------------------------------------------------------------------
# **人口上限：初始 5，升到 3 级变 6，升到 5 级变 7，常规对局最多 7。**
# 重要推论：**并不是每次升级都能解人口**。2→3 和 4→5 才涨人口，
# 其余几级升上去人口纹丝不动 —— 所以"人口满了就升级"这条捷径必须先查这张表，
# 否则会在 3 级人口满时白花一次升级费（那一级升到 4 还是 6 人口）。
POP_CAP_BY_LEVEL = {1: 5, 2: 5, 3: 6, 4: 6, 5: 7, 6: 7}
POP_CAP_DEFAULT = 5


def pop_cap_at(level: int) -> int:
    """该等级的人口上限。等级未知时给初始值 5。"""
    return POP_CAP_BY_LEVEL.get(level, POP_CAP_DEFAULT)


def level_floor_from_pop_cap(cap: int) -> int:
    """从**人口上限**反推棋手等级的下限。

    官方表：人口上限 5/5/6/6/7/7 对应 1~6 级 —— 所以 cap=6 至少 3 级，cap=7 至少 5 级。
    为什么需要它：等级徽章是"数亮点"，**高等级时花瓣会连成一片**（6 点糊成一块），
    而且有的状态下点是彩色的，灰度阈值读不到 —— 实测后期一路返回 -1 或 1，
    于是 `state.level` 卡在旧值，搜牌期/品阶池的判断跟着失准。
    人口上限是 OCR 数字、读得稳，拿它兜底比继续调徽章阈值划算得多。
    """
    if cap >= 7:
        return 5
    if cap >= 6:
        return 3
    return 1


def level_raises_pop(level: int) -> bool:
    """从 `level` 再升一级，人口上限会不会涨。"""
    return pop_cap_at(level + 1) > pop_cap_at(level)


