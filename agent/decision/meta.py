# 棋手经验（2026-09-22 补充）
# ---------------------------------------------------------------------------
# 1. 每回合结束 +1 经验，**稳定给**。
# 2. 拍卖结束**额外** +2（第 4/8/12 回合开头的拍卖，即第 3/7/11 回合结束时）→ 合计 3 点。
#    （两份资料对这点的说法不同：一份说"战斗+1／拍卖+3、不叠加"，另一份说
#     "每回合+1／拍卖额外+2"。**合计都是 3**，所以 lord_xp_gain 不受影响；
#     这里按后者记，因为它同时解释了"非拍卖回合也稳定 +1"。）
# 3. **弈星在场时，棋手升级会额外给经验；弈星是觉醒牌时效果翻倍**。
# 4. 升级所需经验**按等级递增**（具体阈值表未知，没有可靠来源，别瞎填）。
#
# 关键推论：**棋手会自己攒经验、攒满自动升级，并自动弹出天赋三选一**。
# 也就是说天赋弹窗不需要我们点「升级」也会出现，主循环必须随时能接住它
# （2026-09-22 第十一局就是在这里卡死的：三选一选对了，卡在选完的放大详情上）。
LORD_XP_BATTLE = 1
LORD_XP_AUCTION = 3


def lord_xp_gain(round_no: int) -> int:
    """这一回合结束时棋手能拿到多少经验（两类不叠加，拍卖回合只算 3）。"""
    if round_no <= 0:
        return 0
    # 拍卖夹在第 A-1 回合战斗和第 A 回合准备之间 → 拍卖经验算在第 A-1 回合结束时
    return LORD_XP_AUCTION if round_no + 1 in AUCTION_ROUNDS else LORD_XP_BATTLE


