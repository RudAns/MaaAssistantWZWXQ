@card("兵行诡招")
class 兵行诡招:
    """棋手生命值-10，战斗开始时，己方每名英雄+2临时等级。战斗胜利时，获得1棋手生命值，临时等级额外+1。
    实现：拿到时 生命 -10；每场战斗开始给每名英雄（含视为英雄的召唤单位）+(2+额外) 临时等级；
    每次战斗胜利 生命 +1、以后的"额外"+1（累加）。
    待核对："临时等级额外+1"按"以后每场战斗开始多给 1 级、可累加"实现（最自然：临时等级战后清零，胜利当场 +1 没有意义）
    —— 也可能只是本场胜利时 +1（那样只对明世隐转化有意义）。生命值回复不超过 60（engine.add_hp，待核对）。"""
    def on_use(self, eng, t):
        eng.add_hp(-10, src="兵行诡招")

    def react_battle_start(self, eng, holder, unit=None, **kw):
        if unit is None or unit.kind != "hero" or unit not in eng.s.units:
            return
        eng.temp(unit, 2 + eng.s.flags.get("兵行诡招_extra", 0), src="兵行诡招")

    def on_battle_end(self, eng, holder, win=False):
        if win:
            eng.add_hp(1, src="兵行诡招")
            eng.s.flags["兵行诡招_extra"] = eng.s.flags.get("兵行诡招_extra", 0) + 1


