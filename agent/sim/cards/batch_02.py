@card("不屈意志")
class 不屈意志:
    """唯一。战斗开始及之后每3秒获得场上友军穿戴不屈意志数量x2的临时等级。阵亡时，将自身等级的30%平均分配给穿戴不屈意志的友军。
    实现：战斗开始一次性给 (场上穿戴不屈意志的单位数，含自己) × 2 × 次数 的临时等级，次数 = 1 + 20 秒 // 3 秒 = 7；
    阵亡时把自身永久等级的 30% 平均分给场上其他穿戴者（永久等级，自身不扣）。
    待核对：①"友军数量"含不含自己（按含）；② 阵亡后停止叠加（引擎不知道阵亡时刻，按打满一场 20 秒）；
    ③ 分出去的是永久还是临时等级（卡面没写"临时"→ 按永久）、自身是否扣掉（按不扣）、取不取整（按不取整）。"""
    def on_battle_start(self, eng, u):
        if u not in eng.s.units:
            return
        n = sum(1 for x in eng.s.on_board() if "不屈意志" in x.equips)
        ticks = 1 + BATTLE_SECONDS // 3
        eng.temp(u, 2 * n * ticks, src="不屈意志")

    def on_death(self, eng, u):
        mates = [x for x in eng.s.on_board() if x is not u and "不屈意志" in x.equips]
        if not mates:
            return
        share = u.level * 0.3 / len(mates)
        for x in mates:
            eng.level(x, share, src="不屈意志")


