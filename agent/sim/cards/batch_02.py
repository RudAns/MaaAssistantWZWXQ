# ============================================================ 辅助
def _effect_cards(tier: int) -> list:
    return [n for n, c in card_db().items() if c.get("category") == "效果牌" and quality(n) == tier]


def random_effect_card(eng) -> str | None:
    """随机 1 张效果牌：品阶 = min(棋手等级, 5)（和效果锦囊同口径），按历史 N 选 1 出现频率抽
    （data/engine/draw_stats.json）；没有统计就在该品阶效果牌里均匀抽。"""
    tier = max(1, min(eng.s.lord_level, 5))
    try:
        from agent.engine.rollout import draw_stats
        st = ((draw_stats().get("jinnang") or {}).get(str(tier)) or {}).get("cards") or {}
    except Exception:  # noqa: BLE001
        st = {}
    if st:
        names, ws = list(st), list(st.values())
        return eng.rng.choices(names, ws)[0]
    pool = _effect_cards(tier)
    return eng.pick(pool, 1)[0] if pool else None


