@card("捕能手套")
class 捕能手套:
    """唯一。每击败1名英雄，获得1能量。单回合击败不少于5名英雄时，获得能量转换。能量转换：消耗3能量，获得与棋手等级相对应的效果锦囊牌（不超过5阶）。
    实现：穿戴者击杀 n 名 → 能量 +n；本回合累计 ≥5 → 获得 1 张「能量转换」（每回合限一次）。
    待核对：引擎的"击杀"不区分英雄 / 召唤物（按全算英雄）；"获得能量转换"按获得 1 张效果牌（能量转换的实现在别的批次）。"""
    def on_kill(self, eng, u, n=0):
        if not n:
            return
        eng.s.energy += n
        key = f"round:捕能手套:{u.uid}"
        got = eng.s.flags.get(key, 0) + n
        eng.s.flags[key] = got
        if got >= 5 and not eng.s.flags.get(key + ":given"):
            eng.s.flags[key + ":given"] = True
            eng.gain_card("能量转换")


