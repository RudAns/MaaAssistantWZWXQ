@card("绝处逢生")
class 绝处逢生:
    """棋手生命值变为1，随机获得10张效果牌。
    待核对："随机效果牌"的品阶与池子 —— 按"品阶 = min(棋手等级,5)、按锦囊历史出现频率抽"实现；手牌满了多出的丢掉（gain_card 的口径）。"""
    def on_use(self, eng, t):
        eng.add_hp(set_to=1, src="绝处逢生")
        for _ in range(10):
            x = random_effect_card(eng)
            if x:
                eng.gain_card(x)


@card("化铁为金")
class 化铁为金:
    """指定1名1-3阶的英雄随机变为不在场的5阶英雄，觉醒并保留其当前等级（包括临时等级）。
    实现：改名为随机 1 名不在场的 5 阶英雄（按牌库剩余张数加权），觉醒进度置满，等级 / 临时等级 / 装备 / 格子不变；
    枫叶舞绑定、主C 记的是名字，一并改成新名字（eng.rename）。
    10-19 确认的规则：变出的觉醒英雄直接上场、触发登场 → 变身后触发一次登场（eng.trigger：被触发的登场，不算"使用英雄牌"）。
    待核对：变身是否从牌库拿走一张、原卡是否放回牌库（按都不动实现）；装备是否保留（按保留）；登场算不算"使用英雄牌"（按不算）。"""
    def on_use(self, eng, t):
        if t is None or t not in eng.s.units or t.kind != "hero" or not (1 <= quality(t.name) <= 3):
            return False
        on = {x.name for x in eng.s.units}
        names = [n for n, c in card_db().items() if c.get("category") == "英雄牌" and quality(n) == 5 and n not in on]
        if not names:
            return False
        ws = [eng.pool_left(n) for n in names]
        new = eng.rng.choices(names, ws)[0] if sum(ws) > 0 else eng.pick(names, 1)[0]
        eng.rename(t, new, src="化铁为金")
        t.awaken = max(t.awaken, 3)
        eng.trigger(t, "deploy")                           # 10-19 确认：化铁为金变出的觉醒英雄直接上场触发登场


