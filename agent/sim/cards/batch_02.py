@card("四人同行")
class 四人同行:
    """卡牌5选1，并将选中的卡牌一分为四。
    实现：按棋手等级的商店品阶概率、牌库剩余张数抽 5 张不同英雄牌 → 推演打法选 1 → 获得 4 张同名，牌库记拿走 1 张。
    待核对：5 选 1 的池子（是否只有英雄牌、是否会出效果牌 / 装备牌）与品阶；一分为四是否从牌库扣 4 张（按扣 1 张）。"""
    def on_use(self, eng, t):
        opts = []
        for _ in range(40):
            x = eng.draw_hero(None)
            if x and x not in opts:
                opts.append(x)
            if len(opts) >= 5:
                break
        pick = eng.choose("four_together", opts)
        if not pick:
            return
        eng.take(pick)
        for _ in range(4):
            eng.gain_card(pick)


